// VA: AppleIntelTGLGraphicsVADriver lists yuv2 and NV12 as video-processing
// outputs. Clearing the count of that one list makes AppleGVA use its non-VPHAL
// path instead of the media-object stream that stalls RCS on streamed video
// (b00t0x/WhateverXe#81).
// XFER: the same driver lists NV12/BGRA/yuvs... pixel-transfer outputs for its two
// video-processing contexts (0x200 and 0x800) that AppleGVA creates for scaling and
// colour conversion. Creating one dereferences a render component the driver never
// allocates (VA +0x1336f3, NULL+8), crashing WindowServer, QuickTime and
// mediaanalysisd (b00t0x/WhateverXe#23). Clearing both output counts makes AppleGVA
// use its software path, as it does when the driver is absent.
// MTL: -[MTLIGAccelCommandBuffer dealloc] skips deleting the command buffer's
// private POSH buffer when it was the queue's only active one, leaking 76 KB per
// command buffer (b00t0x/WhateverXe#47).
// NULLGUARD: the alternative to XFER. The driver allocates only pRender[COMPOSITE]
// (+0x920); pRender[VEBOX] and pRender[VEBOX2] (+0x910, +0x918) stay NULL, and three
// places still use them: the status-block hookup at +0x1336f3 (the crash above), the
// render preparation at +0x130e91 and the VEBOX render step at +0x12d316. Each gets an
// in-place test of the loaded pointer, so a non-NULL slot behaves exactly as before
// and a NULL one skips only that store or call (the render step returns its own
// MOS_STATUS_NULL_POINTER). Contexts keep being created, so AppleGVA's scaler works
// and VideoToolbox can use the hardware encoder, which XFER stops by making every
// scaler context fail. Ported from SaqibAlMalik/WhateverXe (tgl-stability-0.8.2,
// kern_va_fix.hpp, BSD-3-Clause), where it is -wex-va-nullguard. The pages are
// matched by one exact window each, so the fix needs no per-build digest.
// Measured on an i5-1145G7 (Sequoia, Graphics 0.4.0) with tools/vtransfer_check:
// no crash, but the VEBOX render step still has no component, so every transfer that
// needs it (420v and BGRA scaling or conversion, 8 of the 12 cases) returns status 0
// with the output untouched ("Error scheduling command"), where XFER produces correct
// frames in software. Use it only to try the hardware encoder, never as the daily fix.
// GVAASSERT: the fix for the WindowServer crash when AppleGVA cannot build a video
// pipeline (2026-11-15, AirPlay mirroring: "Assertion failed: (assertOnError == false),
// function createPipeline8bit, file branch_PP0.cpp, line 358"). AppleGVACore lives in
// the dyld shared cache, not in /Library/GPUBundles. Flow_PP0 keeps a byte at +0x349
// that kAVF_PP0_IOServiceInfo sets to 1 (setParam, VMA 0x7ffa0635e99a in 24H32), and
// every other use only reads it: it is passed as assertOnError to createPipeline8bit,
// createPipeline10bit and createPipeline, and tested before Flow_PP0::pushMetaData's
// own asserts. With it set a failing pipeline (which -wexvafix makes certain for the
// 420v -> BGRA scaler that WindowServer asks for) aborts WindowServer; with it clear
// the same code returns the error and the caller falls back. The fix stores 0 instead
// of 1 in that one instruction (1 byte). Matched by one exact window at a pinned file
// offset of dyld_shared_cache_x86_64h.02 (macOS 15.8.1, 24H32), so it is inert on any
// other cache build.
// GVACONFIGURE: the second half of the same fix. With assertOnError clear createPipeline
// returns its error, which reaches AVFPixelProcessCore_PrepareToTransferImages through
// configureFlow, and there two `jne` instructions (VMA 0x7ffa0635c146 and 0x7ffa0635c22d)
// jump to an unconditional `assert(0)` in AVF_PixelProcessCore.cpp
// ("GVA error: AVFPixelProcessCore_PrepareToTransferImages configureFlow"), which aborted
// WindowServer again (2026-11-15 02:21, uptime 94 s). Both now jump to the function's own
// "unsupported" return (movl $0xffffd43c, %r14d; jmp epilogue) so PrepareToTransferImages
// returns that error; WindowServer's transfer_image_async logs it and returns false.
// One 244-byte window of page 0x635c000 changes 3 bytes.
// Pages are matched by file offset, fields and a full SHA-256, once the kernel
// has validated them, so the signed bundles stay untouched.
// VFE (-wexvfe): the AppleIntelTGLGraphicsVADriver (Intel media-driver code, MhwRenderInterfaceG12) builds its media
// pipeline with two leftovers from older generations that Gen12 does not have, which is why the VP batch (MEDIA_OBJECT
// stream on RCS) never completes: "VFE, TSG0, CS not finished" in the hang reports (b00t0x/WhateverXe#23, #81).
// L3: the media L3 setup emits MI_LOAD_REGISTER_IMM with the packed qword 0x80000040'00000000, that is data 0x80000040
// into register offset 0; the Gen12 register is L3ALLOCREG (0xB134) and the media value is 0xD0000020 (VA file offset
// 0x1c2a, `movabs $imm64, %rax` stored at +4 of the command). VFEL3 rewrites the immediate.
// MEDIA_VFE_STATE: Gen11/12 has no scoreboard (Mesa genxml: DW3 threads/URB, DW5 CURBE/URB sizes, DW6-8 unused), but the
// state builder (VA 0x2c956..0x2ca57) still copies a 9-dword template whose DW6-DW8 are the old scoreboard mask and
// deltas (0x31d720: DW6 0xff, DW7 0xfff1f00f, DW8 0xefe1e01f) and then sets the scoreboard enable (DW6 bit 31, or
// 0x80000001 with DW7 0xf/0xf0 per walker mode). VFETemplate zeroes DW6-DW8 of the template, VFESites turns the three
// stores into no-ops (`orb $0x80, 0x1b` becomes `andl $0, DW6`, the two `movq %r10/%r11, DW6` become 4-byte nops).
// Same Mach-O file offsets in Graphics 0.4.0 and 0.4.4 (16.0.32). Matched by exact windows only. Not derived from the
// upstream tables (b00t0x/WhateverXe 7b0138a, Raptor Lake-P): the "independent EU dispatch" bit they also set is not
// reproduced here because its position is not known.
// NULLSKIP (-wexnullskip, needs -wexnullguard): the VEBOX render step runs for the primary layer of every pass
// (`cmpl $2, 0x134(%rcx)`: VPHAL SurfType 2 = SURF_IN_PRIMARY) and, with no VEBOX component, -wexnullguard makes it return
// MOS_STATUS_NULL_POINTER (`movl $5, -0x1c(%rbp)` at VA 0x12d336), so 420v and BGRA conversions fail with "Error scheduling
// command" and write nothing. With the result 0 the step reports success without a VEBOX output (the flag at +0x20 stays
// clear and the caller returns), and the pass continues in the COMPOSITE renderer that already handles yuvs and 2vuy.
// CMFCVERSION (-wexcmfc): the Fast Composite kernels of the VA driver are shipped as `CMPI` blobs (hundreds of them, all with
// the 16-bit version 13 at offset 6), but the blob validator at VA 0x1ee5e0 only accepts versions 1..8 (`decl %ecx; subl $7;
// ja`), so every one of them is rejected and CompositeState::Render (VA 0x1181b0) returns MOS_STATUS_UNKNOWN 0x1f for any layer
// that is not yuvs or 2vuy (420v, BGRA): "Error scheduling command 0". The window turns the test into `subl $13` (valid when the
// version is at most 13). Found with lldb on vtransfer_check under -wexnullguard -wexnullskip (2026-11-15).
